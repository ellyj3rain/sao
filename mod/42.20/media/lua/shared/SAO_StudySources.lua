local function copy(v)
    if type(v)~="table" then return v end
    local out={} for k,x in pairs(v) do out[k]=copy(x) end return out
end
local function definition(sourceId)
    for full,d in pairs(definitions) do if d.id==sourceId then return d,full end end
end
function L.definition(fullType) return copy(definitions[fullType]) end
function L.source(sourceId) return copy(definition(sourceId)) end
function L.relevance(sourceId)
    local d=definition(sourceId)
    local ok,year=pcall(function() return getGameTime():getYear() end)
    return {sourceId=sourceId,worldYear=ok and year or nil,
        status=d and ok and type(year)=="number" and year>=d.editionYear and "fictional-edition-available"
            or "world-date-unavailable-or-before-edition",historicalPublication=false}
end
function L.matches(sourceId,revision,hash,pages)
    local d=definition(sourceId)
    if not d or d.revision~=revision or d.textHash~=hash or type(pages)~="table" or #pages~=#d.pages then return false end
    for index,text in ipairs(d.pages) do if pages[index]~=text then return false end end
    return true
end
function L.binding(item)
    local ok,row=pcall(function()
        local d=definitions[item:getFullType()]
        if not d or item:isEmptyPages() or item:getCustomPages():size()~=#d.pages then return nil end
        local b=item:getModData().SAOLiterature
        if type(b)~="table" or b.itemId~=tostring(item:getID()) or b.fullType~=item:getFullType()
            or b.sourceId~=d.id or b.revision~=d.revision or b.textHash~=d.textHash
            or b.authoredDate~=d.authoredDate or b.authorship~=d.authorship or b.license~=d.license
            or b.edition~=d.edition or b.historicalPublication~=false then return nil end
        for index,text in ipairs(d.pages) do if item:seePage(index)~=text then return nil end end
        local out=copy(b);out.relevance=L.relevance(d.id)
        return out.relevance.status=="fictional-edition-available" and out or nil
    end)
    return ok and row or nil
end
-- Native OnCreate may be revisited. A populated or previously bound item is
-- validated, never rewritten or silently upgraded into the selected revision.
function SAO_Literature_OnCreate(item)
    local d=definitions[item:getFullType()]
    if not d then return false end
    item:setName("Buildings, routes and upkeep: "..d.topic)
    local data=item:getModData()
    if data.SAOLiterature~=nil then return L.binding(item)~=nil end
    if not item:isEmptyPages() then return false end
    for index,text in ipairs(d.pages) do item:addPage(index,text) end
    data.SAOLiterature={sourceId=d.id,revision=d.revision,textHash=d.textHash,itemId=tostring(item:getID()),
        fullType=item:getFullType(),authoredDate=d.authoredDate,authorship=d.authorship,license=d.license,
        edition=d.edition,historicalPublication=false}
    -- Native creation can precede an available world date; page integrity and
    -- edition availability are queried separately when exposure is admitted.
    return true
end
