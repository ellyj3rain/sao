-- The response producer receives answer-free tasks. Held projections and
-- numeric expected answers stay in this scoring closure.
function L.task(sourceId,mode)
    local d=definition(sourceId)
    if not d or mode~="comprehension" and mode~="retrieval" and mode~="transfer" then return nil end
    if d.topic=="civilian" then
        return {id="room-possibilities",kind="literal-relations",mode=mode,subject="room",
            prompt="Recall the explicitly declared conditional associations in this source.",
            scoreMeaning="bounded-literal-association-reconstruction; semantic explanation unscored"}
    end
    local stock,draw=mode=="transfer" and 35 or d.topic=="engineering" and 12 or 18,
        mode=="transfer" and 5 or d.topic=="engineering" and 3 or 6
    return {id="stock-interval",kind="interval-and-relations",mode=mode,stock=stock,dailyDraw=draw,
        prompt="Using the supplied hypothetical stock and daily draw, compute days if there are no other draws or losses. Recall the conditional associations in this source.",
        scoreMeaning="stated-quantity-arithmetic-and-literal-reconstruction; strategy unscored"}
end
function L.hasRelation(sourceId,revision,hash,edge)
    local d=definition(sourceId)
    if not d or d.revision~=revision or d.textHash~=hash or type(edge)~="table" then return false end
    for _,row in ipairs(projections[d.topic] or {}) do
        if row.from==edge.from and row.relation==edge.relation and row.into==edge.into and edge.affirmed~=false then return true end
    end
    return false
end
local function sameEdge(a,b)
    return type(a)=="table" and a.from==b.from and a.relation==b.relation and a.into==b.into and a.affirmed~=false
end
function L.grade(sourceId,task,response)
    local d=definition(sourceId)
    local held=d and L.task(sourceId,task and task.mode)
    if not held or task.id~=held.id or task.kind~=held.kind or task.stock~=held.stock or task.dailyDraw~=held.dailyDraw
        or type(response)~="table" then return {status="unscored",reason="unsupported-response"} end
    if response.kind~="structured-reconstruction" or type(response.relations)~="table" then
        return {status="unscored",reason="semantic-response-has-no-owned-grader"}
    end
    local required=projections[d.topic]
    local correct=task.kind=="literal-relations" or response.days==held.stock/held.dailyDraw
    for _,edge in ipairs(required) do
        local found=false
        for _,row in ipairs(response.relations) do if sameEdge(row,edge) then found=true;break end end
        if not found then correct=false end
    end
    for _,row in ipairs(response.relations) do
        local found=false for _,edge in ipairs(required) do if sameEdge(row,edge) then found=true;break end end
        if not found then correct=false end
    end
    return {status=correct and "passed" or "failed",relations=correct and copy(required) or {},
        meaning=held.scoreMeaning,semanticExplanation="unscored",rubricRevision=1}
end
